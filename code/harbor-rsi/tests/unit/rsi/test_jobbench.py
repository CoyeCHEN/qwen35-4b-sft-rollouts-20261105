EVAL_ROOT = Path(__file__).resolve().parents[3] / "benchmarks"
JOBBENCH_ROOT = EVAL_ROOT / "jobbench"
sys.path.insert(0, str(JOBBENCH_ROOT / "src"))

from jobbench_e2b import adapter  # noqa: E402


def _source_task(root: Path) -> Path:
    task = root / "dataset" / "easy" / "analysts" / "task1"
    fixture = task / "task_folder"
    fixture.mkdir(parents=True)
    (fixture / "TASK_INSTRUCTIONS.txt").write_text(
        "Create report.txt in the output directory.\n", encoding="utf-8"
    )
    (fixture / "input.csv").write_text("name,value\na,1\n", encoding="utf-8")
    (task / "RUBRICS.json").write_text(
        json.dumps({"rubrics": [{"id": "r1", "weight": 10, "criteria": "report"}]}),
        encoding="utf-8",
    )
    (task / "task_card.md").write_text("grader-only answer", encoding="utf-8")
    (task / "files_required_to_search").mkdir()
    (task / "files_required_to_search" / "answer.txt").write_text(
        "must not leak", encoding="utf-8"
    )
    return task


def test_pinned_judge_hash_matches_attachment():
    import pytest

    if not (adapter.VENDOR_DIR / "judge.py").exists():
        pytest.skip("Run benchmarks/scripts/fetch-jobbench-judge.py first")
    assert (
        adapter.sha256_file(adapter.VENDOR_DIR / "judge.py") == adapter.EVALUATOR_SHA256
    )
    assert adapter.load_judge().startswith("#!/usr/bin/env python")


def test_adapter_generates_valid_openharness_e2b_task(tmp_path, monkeypatch):
    monkeypatch.setattr(adapter, "load_judge", lambda: "# fixture judge\n")
    monkeypatch.setattr(adapter, "sha256_file", lambda _: adapter.EVALUATOR_SHA256)
    source = tmp_path / "source"
    _source_task(source)
    output = tmp_path / "generated"
    monkeypatch.setitem(adapter.SPLITS, "easy", (("dataset/easy",), 1))

    manifest = adapter.run(
        source_root=source,
        output_root=output,
        splits=["easy"],
        base_image=None,
        workdir="/workspace",
        overwrite=False,
    )

    assert manifest["splits"]["easy"]["count"] == 1
    generated = output / "easy" / "analysts__task1"
    cfg = tomllib.loads((generated / "task.toml").read_text(encoding="utf-8"))
    assert cfg["metadata"]["network_required"] is True
    assert cfg["environment"]["workdir"] == "/workspace"
    assert "docker_image" not in cfg["environment"]
    assert cfg["verifier"]["env"]["JUDGE_API_KEY"] == "${JUDGE_API_KEY}"

    dockerfile = (generated / "environment" / "Dockerfile").read_text(encoding="utf-8")
    assert dockerfile.startswith("# Generated by jobbench_e2b.adapter")
    assert "FROM python:3.12-slim-bookworm" in dockerfile
    assert "ripgrep" in dockerfile and "fd-find" in dockerfile
    assert "claude-code" not in dockerfile
    assert "<<'PY'" not in dockerfile
    assert (
        "ln -sf /opt/jobbench-venv/bin/python /usr/local/bin/python3" not in dockerfile
    )
    assert 'ENV PATH="/opt/jobbench-venv/bin:${PATH}"' in dockerfile

    environment = generated / "environment"
    assert not (environment / "task_card.md").exists()
    assert not (environment / "files_required_to_search").exists()
    assert not (environment / "RUBRICS.json").exists()
    assert (generated / "tests" / "judge.py").is_file()

    result = subprocess.run(
        [
            sys.executable,
            str(JOBBENCH_ROOT / "scripts" / "validate_dataset.py"),
            str(generated),
            "--strict",
        ],
        check=False,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "OK" in result.stdout


def test_verifier_uses_weighted_normalized_score():
    path = (
        JOBBENCH_ROOT
        / "src"
        / "jobbench_e2b"
        / "task-template"
        / "tests"
        / "jobbench_verify.py"
    )
    spec = importlib.util.spec_from_file_location("jobbench_verify", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)

    assert module.normalize({"total_score": 30, "max_score": 40}) == 0.75
    assert module.normalize({"total_score": 0, "max_score": 0}) == 0.0
    assert (
        module.count_infra_failures(
            {
                "total_count": 2,
                "rubrics": [
                    {"result": {"overall_reasoning": "Failed after 3 retries"}}
                ],
            }
        )
        == 2
    )


def test_empty_submission_writes_zero_native_reward(tmp_path, monkeypatch):
    path = (
        JOBBENCH_ROOT
        / "src"
        / "jobbench_e2b"
        / "task-template"
        / "tests"
        / "jobbench_verify.py"
    )
    spec = importlib.util.spec_from_file_location("jobbench_verify_empty", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)

    output = tmp_path / "output"
    output.mkdir()
    rubrics = tmp_path / "RUBRICS.json"
    rubrics.write_text(
        json.dumps(
            {
                "rubrics": [
                    {"id": "r1", "weight": 10},
                    {"id": "r2", "weight": 20},
                ]
            }
        ),
        encoding="utf-8",
    )
    verifier_dir = tmp_path / "logs" / "verifier"
    monkeypatch.setattr(module, "VERIFIER_DIR", verifier_dir)
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "jobbench_verify.py",
            "--output-dir",
            str(output),
            "--rubrics",
            str(rubrics),
            "--judge",
            str(JOBBENCH_ROOT / "vendor" / "judge.py"),
            "--task-id",
            "analysts/task1",
            "--profession",
            "analysts",
            "--evaluated-model",
            "baseline-v1",
            "--judge-model",
            "unused-for-empty-output",
        ],
    )

    assert module.main() == 0
    rewards = json.loads((verifier_dir / "reward.json").read_text(encoding="utf-8"))
    report = json.loads(
        (verifier_dir / "jobbench_result.json").read_text(encoding="utf-8")
    )
    assert rewards["reward"] == 0.0
    assert rewards["jobbench_max_score"] == 30.0
    assert report["status"] == "empty_output"
